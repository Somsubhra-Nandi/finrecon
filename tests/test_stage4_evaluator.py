class TestCohortReconstruction:
    def test_an_exact_cohort_is_reconstructed_from_multiple_sources(
        self, benchmark_dir, corpus, tmp_path
    ):
        """The real workflow: one source is short, a second covers the gap."""
        records = load_cache_dir(corpus["dir"])
        by_case = {r.case_id: r for r in records}
        wanted = corpus["t2"]
        first = [by_case[c] for c in wanted[: len(wanted) - 3]]
        second = [by_case[c] for c in wanted[len(wanted) - 3 :]]

        assembled = assemble([first, second])
        assert set(assembled.case_ids) == set(wanted)
        assert assembled.duplicates == {}
        assert sum(assembled.per_source_counts.values()) == len(wanted)

    def test_a_case_offered_by_two_sources_is_reported_as_a_duplicate(self, corpus):
        records = load_cache_dir(corpus["dir"])
        overlap = records[:3]
        assembled = assemble([records, overlap])
        assert set(assembled.duplicates) == {r.case_id for r in overlap}
        for labels in assembled.duplicates.values():
            assert len(labels) == 2

    def test_first_source_wins_and_later_sources_only_fill_gaps(self, corpus):
        records = load_cache_dir(corpus["dir"])
        a, b = records[:2], records[1:3]
        assembled = assemble([a, b])
        assert assembled.records[records[1].case_id].source == a[1].source

    def test_a_duplicate_in_the_requested_cohort_is_rejected(
        self, benchmark_dir, corpus
    ):
        ground_truth = load_ground_truth(benchmark_dir, "dev")
        repeated = (*corpus["t2"], corpus["t2"][0])
        report = build_cohort(
            requested=repeated,
            available=corpus["all"],
            duplicate_sources={},
            ground_truth=ground_truth,
        )
        assert report.duplicate_requested == (corpus["t2"][0],)
        with pytest.raises(CohortError, match="duplicate case IDs"):
            enforce(report, require_exact=True, require_tier=False)

    def test_a_missing_case_fails_an_exact_cohort(self, benchmark_dir, corpus):
        ground_truth = load_ground_truth(benchmark_dir, "dev")
        report = build_cohort(
            requested=(*corpus["t2"], "case:bnk_dev_000999"),
            available=corpus["all"],
            duplicate_sources={},
            ground_truth=ground_truth,
        )
        assert report.missing == ("case:bnk_dev_000999",)
        assert not report.complete
        with pytest.raises(CohortError):
            enforce(report, require_exact=True, require_tier=False)

    def test_an_unscorable_case_is_always_fatal(self, benchmark_dir, corpus):
        """No ground-truth row means no score, exact cohort or not."""
        ground_truth = load_ground_truth(benchmark_dir, "dev")
        ground_truth.pop(corpus["t2"][0])
        report = build_cohort(
            requested=None,
            available=corpus["t2"],
            duplicate_sources={},
            ground_truth=ground_truth,
        )
        assert report.unknown_to_ground_truth == (corpus["t2"][0],)
        with pytest.raises(CohortError, match="no ground-truth row"):
            enforce(report, require_exact=False, require_tier=False)

    def test_extra_available_cases_are_reported_and_not_scored(
        self, benchmark_dir, corpus
    ):
        ground_truth = load_ground_truth(benchmark_dir, "dev")
        report = build_cohort(
            requested=corpus["t2"],
            available=corpus["all"],
            duplicate_sources={},
            ground_truth=ground_truth,
        )
        assert set(report.extra) == set(corpus["t3"])
        assert set(report.case_ids) == set(corpus["t2"])


class TestTierContamination:
    def test_a_clean_t2_cohort_reports_no_contamination(self, t2_evaluation):
        cohort = t2_evaluation.report["cohort"]
        assert cohort["tier_counts"] == {"T2": T2_SAMPLE}
        assert cohort["all_expected_tier"] is True
        assert cohort["contamination"] == []

    def test_a_t3_case_in_a_t2_cohort_is_detected_and_fatal(
        self, benchmark_dir, corpus
    ):
        ground_truth = load_ground_truth(benchmark_dir, "dev")
        polluted = (*corpus["t2"], corpus["t3"][0])
        report = build_cohort(
            requested=polluted,
            available=corpus["all"],
            duplicate_sources={},
            ground_truth=ground_truth,
            expected_tier="T2",
        )
        assert report.tier_counts == {"T2": T2_SAMPLE, "T3": 1}
        assert report.all_expected_tier is False
        assert [c["case_id"] for c in report.contamination] == [corpus["t3"][0]]
        with pytest.raises(CohortError, match="pinned to T2"):
            enforce(report, require_exact=True, require_tier=True)

    def test_contamination_can_be_reported_without_failing(self, benchmark_dir, corpus):
        ground_truth = load_ground_truth(benchmark_dir, "dev")
        report = build_cohort(
            requested=(*corpus["t2"], corpus["t3"][0]),
            available=corpus["all"],
            duplicate_sources={},
            ground_truth=ground_truth,
            expected_tier="T2",
        )
        enforce(report, require_exact=True, require_tier=False)
        assert report.contamination


