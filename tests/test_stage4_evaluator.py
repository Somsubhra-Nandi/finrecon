class TestOfflineGuarantee:
    PROVIDER_NAMES = (
        "openrouter",
        "gorouter",
        "groq",
        "gemini",
        "openai_compatible",
    )

    def _eval_sources(self) -> list[Path]:
        import benchmark.eval as package

        root = Path(package.__file__).resolve().parent
        return sorted(root.rglob("*.py"))

    def test_the_evaluator_package_has_files_to_check(self):
        assert len(self._eval_sources()) >= 8

    def test_no_evaluator_module_imports_a_provider(self):
        """Structural: the package cannot call a model because it never imports one."""
        for path in self._eval_sources():
            tree = ast.parse(path.read_text(encoding="utf-8"))
            for node in ast.walk(tree):
                module = None
                if isinstance(node, ast.ImportFrom):
                    module = node.module or ""
                elif isinstance(node, ast.Import):
                    module = node.names[0].name
                if module and "agent.providers" in module:
                    pytest.fail(f"{path.name} imports a provider module: {module}")
                if module:
                    for name in self.PROVIDER_NAMES:
                        assert not module.endswith(f"providers.{name}"), path.name

    def test_evaluation_makes_zero_provider_calls(self, t2_evaluation):
        assert t2_evaluation.report["offline_guarantee"]["provider_calls_made"] is False
        assert t2_evaluation.replay.provider_calls_made is False
        assert t2_evaluation.replay.cache_hits == T2_SAMPLE
        assert t2_evaluation.report["configuration"]["provider_constructed"] is False
        assert t2_evaluation.report["configuration"]["offline"] is True

    def test_the_underlying_stage_three_result_reports_no_provider_calls(
        self, t2_evaluation
    ):
        assert t2_evaluation.replay.stage3.provider_calls_made() is False
        assert t2_evaluation.replay.stage3.cache_hits() == T2_SAMPLE

    def test_a_provider_that_raises_on_contact_is_never_contacted(
        self, benchmark_dir, corpus, tmp_path
    ):
        """Belt and braces: replay with a chain whose only provider explodes.

        The evaluator passes ``chain=None``, so this exercises the layer it
        stands on -- if replay ever reached for a provider, this raises.
        """
        from finrecon.agent.providers.chain import ProviderChain
        from finrecon.pipeline import process_batch
        from tests.stage3_fakes import ExplodingProvider

        with LedgerStore(":memory:") as store:
            batch = process_batch(store=store, benchmark_dir=benchmark_dir, split="dev")
            result = run_stage3(
                store=store,
                batch_result=batch,
                chain=ProviderChain((ExplodingProvider(),)),
                cache=TrajectoryCache(corpus["dir"]),
                replay_only=True,
                provider_id=FAKE_PROVIDER,
                model=FAKE_MODEL,
                case_ids=frozenset(corpus["t2"]),
                write_cache=False,
            )
        assert result.cache_hits() == len(corpus["t2"])
        assert not result.provider_calls_made()

    def test_a_missing_trajectory_fails_closed(self, benchmark_dir, corpus, tmp_path):
        config = _config(
            benchmark_dir,
            corpus,
            tmp_path,
            cohort_ids=(*corpus["t2"], "case:bnk_dev_000999"),
        )
        with pytest.raises(CohortError):
            evaluate(config, staging_dir=tmp_path / "stage")

    def test_an_empty_source_list_fails_rather_than_scoring_nothing(
        self, benchmark_dir, tmp_path
    ):
        config = EvaluationConfig(benchmark_dir=benchmark_dir, split="dev")
        with pytest.raises(EvaluationInputError, match="no trajectory source"):
            evaluate(config, staging_dir=tmp_path / "stage")

    def test_a_wrong_cache_identity_is_a_drift_error_not_a_live_run(
        self, benchmark_dir, corpus, tmp_path
    ):
        """Naming another model must never silently re-run the case."""
        config = _config(
            benchmark_dir,
            corpus,
            tmp_path,
            cohort_ids=corpus["t2"],
            model="some-other-model",
        )
