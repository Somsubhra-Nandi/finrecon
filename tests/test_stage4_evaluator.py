class TestSources:
    def test_utf16_dumps_are_decoded_by_bom_not_by_guessing(self):
        """UTF-16LE is valid UTF-8 byte-wise, so a naive ladder would corrupt it."""
        text = "case_id: xyz\n"
        assert decode_text(text.encode("utf-16")) == text
        assert decode_text(text.encode("utf-8")) == text
        assert decode_text(b"\xef\xbb\xbf" + text.encode("utf-8")) == text

    def test_a_run_dump_yields_its_trajectories(self, corpus, tmp_path):
        records = load_cache_dir(corpus["dir"])
        dump = tmp_path / "run.txt"
        body = ["summary header that is not JSON", ""]
        for record in records[:4]:
            body.append("=" * 72)
            body.append(json.dumps(record.payload, indent=2))
        dump.write_text("\n".join(body), encoding="utf-8")

        parsed = load_run_dump(dump)
        assert [r.case_id for r in parsed] == [r.case_id for r in records[:4]]
        assert all(r.source.startswith("dump:") for r in parsed)

    def test_a_dump_with_no_trajectories_fails_loudly(self, tmp_path):
        dump = tmp_path / "empty.txt"
        dump.write_text("investigated: 50\nresolved: 32\n", encoding="utf-8")
        with pytest.raises(EvaluationInputError, match="no trajectory records"):
            load_run_dump(dump)

    def test_a_cohort_can_be_derived_from_a_baseline_dump(self, corpus, tmp_path):
        records = load_cache_dir(corpus["dir"])
        dump = tmp_path / "baseline.txt"
        chunks = ["=" * 72 + "\n" + json.dumps(r.payload) for r in records[:5]]
        dump.write_text("\n".join(chunks), encoding="utf-8")
        assert cohort_from_records(load_run_dump(dump)) == tuple(
            sorted(r.case_id for r in records[:5])
        )

    def test_a_cohort_file_accepts_json_and_plain_lines(self, tmp_path):
        ids = ["case:a", "case:b"]
        as_json = tmp_path / "c.json"
        as_json.write_text(json.dumps(ids), encoding="utf-8")
        as_lines = tmp_path / "c.txt"
        as_lines.write_text("# comment\ncase:a\ncase:b\n", encoding="utf-8")
        wrapped = tmp_path / "w.json"
        wrapped.write_text(json.dumps({"case_ids": ids}), encoding="utf-8")
        assert read_cohort_file(as_json) == ("case:a", "case:b")
        assert read_cohort_file(as_lines) == ("case:a", "case:b")
        assert read_cohort_file(wrapped) == ("case:a", "case:b")

    def test_a_missing_source_fails_closed(self, tmp_path):
        with pytest.raises(EvaluationInputError):
            load_cache_dir(tmp_path / "nope")
        with pytest.raises(EvaluationInputError):
            load_run_dump(tmp_path / "nope.txt")


