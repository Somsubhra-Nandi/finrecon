class TestComparison:
    def test_identical_cohorts_produce_deltas(self, t2_evaluation):
        report = t2_evaluation.report
        result = compare(report, report, label_a="same", label_b="same")
        assert result["cohort_identity"]["identical_case_ids"] is True
        assert result["cohort_identity"]["identical_tier_composition"] is True
        assert result["cohort_identity"]["comparable"] is True
        assert result["side_by_side"]
        for row in result["side_by_side"]:
            assert row["delta"] in (0, 0.0, None)
        assert result["configuration"]["differing_dimensions"] == []

    def test_mismatched_cohorts_are_refused(self, t2_evaluation):
        a = t2_evaluation.report
        b = json.loads(json.dumps(a))
        b["cohort"]["case_ids"] = b["cohort"]["case_ids"][:-1]
        with pytest.raises(CohortError, match="same cases"):
            compare(a, b)

    def test_a_mismatch_can_be_reconciled_without_deltas(self, t2_evaluation):
        a = t2_evaluation.report
        b = json.loads(json.dumps(a))
        b["cohort"]["case_ids"] = b["cohort"]["case_ids"][:-1]
        result = compare(a, b, require_identical_cohort=False)
        assert result["cohort_identity"]["identical_case_ids"] is False
        assert result["side_by_side"] == []
        assert len(result["cohort_identity"]["only_in_a"]) == 1

    def test_differing_tier_composition_blocks_deltas(self, t2_evaluation):
        a = t2_evaluation.report
        b = json.loads(json.dumps(a))
        b["cohort"]["tier_counts"] = {"T3": T2_SAMPLE}
        result = compare(a, b)
        assert result["cohort_identity"]["identical_tier_composition"] is False
        assert result["cohort_identity"]["comparable"] is False
        assert result["side_by_side"] == []

    def test_multiple_changed_dimensions_refuse_causal_attribution(
        self, t2_evaluation
    ):
        a = t2_evaluation.report
        b = json.loads(json.dumps(a))
        # Deliberately values the corpus cannot already have: the fixture is
        # recorded under the *current* prompt and tool versions, so reusing
        # those would silently assert nothing.
        assert b["recorded_versions"]["prompt_version"] != ["investigator.v0"]
        b["recorded_versions"]["prompt_version"] = ["investigator.v0"]
        b["recorded_versions"]["tool_schema_version"] = ["tools.v0"]
        b["telemetry"]["models_requested"] = {"gorouter:claude-opus-5-thinking": 1}
        result = compare(a, b)
        assert result["attribution"]["causal_claim"] is None
        assert result["attribution"]["differing_dimension_count"] == 3
        assert "No outcome difference can be attributed" in (
            result["attribution"]["statement"]
        )
        assert result["configuration"]["single_factor"] is False

    def test_a_single_changed_dimension_is_labelled_but_still_not_asserted(
        self, t2_evaluation
    ):
        a = t2_evaluation.report
        b = json.loads(json.dumps(a))
        b["recorded_versions"]["tool_schema_version"] = ["tools.v0"]
        result = compare(a, b)
        assert result["configuration"]["differing_dimensions"] == [
            "tool_schema_version"
        ]
        assert result["configuration"]["single_factor"] is True
        # Even a clean single-factor difference is not asserted as causal here.
        assert result["attribution"]["causal_claim"] is None


