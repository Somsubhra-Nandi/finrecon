"""Stage 4 — the offline evaluator, and the boundaries it must not cross.

Three groups of tests, answering three different questions.

**Does it measure the right thing?** The evaluator carries the repository's
only non-test definition of "correct auto-resolution", so the first thing
proved here is that it is not a *second* definition: it is checked
case-for-case against the predicate already asserted by
``test_stage3_dev_diagnostic.py::test_no_dev_case_is_auto_resolved_incorrectly``.

**Does it fail when it should?** An evaluator that quietly scores a subset,
or a contaminated cohort, produces a better number than the run deserved.
Every such path is asserted to raise rather than report.

**Does it stay offline and outside the production boundary?** Structurally
(no provider module is imported anywhere in the package; nothing under
``src/finrecon`` imports the package) and at runtime
(``provider_calls_made()`` is false, and a provider that raises on contact is
never contacted).

No test here reaches a network. The corpus is generated by
``tests.stage3_fakes.MechanicalInvestigator``, the same deterministic
non-linguistic stand-in the Stage-3 diagnostics use.
"""

