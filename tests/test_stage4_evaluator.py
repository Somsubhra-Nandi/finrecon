class TestScoring:
    def test_the_t2_cohort_scores_with_no_wrong_resolutions(self, t2_evaluation):
        metrics = t2_evaluation.report["metrics"]
        assert metrics["investigated"] == T2_SAMPLE
        assert metrics["wrong_auto_resolutions"] == 0
        assert metrics["auto_resolved"] == metrics["correct_auto_resolutions"]
        assert metrics["value_at_risk_paise"] == 0
        assert t2_evaluation.report["wrong_resolutions"] == []
        if metrics["auto_resolved"]:
            assert metrics["auto_resolution_accuracy"] == 1.0

    def test_every_resolution_is_correct_against_ground_truth(self, t2_evaluation):
        resolved = [v for v in t2_evaluation.verdicts if v.resolved]
        assert resolved, "the corpus must contain resolutions for this to mean anything"
        for verdict in resolved:
            assert verdict.correct is True
            assert verdict.predicted_settlement_ids == verdict.truth_settlement_ids

    def test_t3_cases_escalate_safely_and_count_as_correct_escalations(
        self, benchmark_dir, corpus, tmp_path
    ):
        config = _config(
            benchmark_dir, corpus, tmp_path, cohort_ids=corpus["t3"], expected_tier="T3"
        )
        result = evaluate(config, staging_dir=tmp_path / "stage")
        metrics = result.report["metrics"]
        assert metrics["auto_resolved"] == 0
        assert metrics["escalated"] == T3_SAMPLE
        assert metrics["wrong_auto_resolutions"] == 0
        assert metrics["truly_ambiguous_cases"] == T3_SAMPLE
        assert metrics["correctly_escalated"] == T3_SAMPLE
        assert metrics["escalation_recall"] == 1.0
        # No resolvable case in the cohort, so match rate is undefined, not zero.
        assert metrics["overall_match_rate"] is None
        assert metrics["auto_resolution_accuracy"] is None

    def test_rates_are_none_rather_than_zero_on_an_empty_denominator(
        self, t2_evaluation
    ):
        for key in ("auto_resolution_accuracy", "overall_match_rate"):
            value = t2_evaluation.report["metrics"][key]
            assert value is None or isinstance(value, float)


