# --- correctness is not redefined -----------------------------------------


class TestCorrectnessSemanticsAreReused:
    def test_the_evaluator_predicate_matches_the_stage_three_diagnostic(
        self, dev_stage3_result, dev_ground_truth
    ):
        """The evaluator must agree with the repo's existing predicate, exactly.

        The comparison predicate below is transcribed from
        ``test_no_dev_case_is_auto_resolved_incorrectly``. If the evaluator
        ever grows its own notion of correctness, this diverges on some case
        and fails -- which is the whole point of asserting it over the full
        DEV residual rather than a sample.
        """
        result, _, _ = dev_stage3_result
        checked = 0
        for outcome in result.resolved():
            expected = dev_ground_truth[outcome.case_id]["correct_relationship"]
            if expected is None:
                reference_wrong = True
            else:
                reference_wrong = (
                    tuple(sorted(expected["settlement_ids"]))
                    != outcome.decision.resolved_settlement_ids
                )

            entry = _entry(dev_ground_truth, outcome.case_id)
            verdict = verdict_for(outcome, entry)
            assert verdict.correct is not reference_wrong, outcome.case_id
            checked += 1
        assert checked > 0

    def test_resolving_a_case_with_no_correct_answer_is_wrong(
        self, dev_stage3_result, dev_ground_truth
    ):
        result, _, _ = dev_stage3_result
        outcome = result.resolved()[0]
        entry = dataclasses.replace(
            _entry(dev_ground_truth, outcome.case_id), correct_relationship=None
        )
        verdict = verdict_for(outcome, entry)
        assert verdict.correct is False
        assert verdict.wrong_reason == WRONG_NO_CORRECT_ANSWER

    def test_resolving_to_another_settlement_is_wrong(
        self, dev_stage3_result, dev_ground_truth
    ):
        result, _, _ = dev_stage3_result
        outcome = result.resolved()[0]
        entry = _entry(dev_ground_truth, outcome.case_id)
        moved = dataclasses.replace(
            entry, correct_relationship={"settlement_ids": ["setl_dev_999999"]}
        )
        verdict = verdict_for(outcome, moved)
        assert verdict.correct is False
        assert verdict.wrong_reason == WRONG_SETTLEMENT
        assert verdict.truth_settlement_ids == ("setl_dev_999999",)
        assert verdict.predicted_candidate_id == outcome.decision.resolved_candidate_id
        assert verdict.termination_reason == outcome.trajectory.termination_reason
        assert verdict.evidence_relations, "a wrong resolution must still name its evidence"


def _entry(ground_truth: dict, case_id: str) -> GroundTruthEntry:
    raw = ground_truth[case_id]
    return GroundTruthEntry(
        case_id=case_id,
        tier=raw["tier"],
        archetype=raw["archetype"],
        required_outcome=raw["required_outcome"],
        correct_relationship=raw["correct_relationship"],
        true_reference=raw["true_reference"],
        value_at_stake_paise=raw["value_at_stake_paise"],
    )


