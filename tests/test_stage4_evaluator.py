@pytest.fixture(scope="session")
def corpus(benchmark_dir, dev_ground_truth, tmp_path_factory):
    """A real recorded trajectory corpus, produced with zero network access.

    Runs the deterministic stand-in over a small DEV slice and lets the
    trajectory cache write the fixtures, which is exactly the artifact shape
    the evaluator consumes in production use.
    """
    from finrecon.agent.providers.chain import ProviderChain
    from finrecon.pipeline import process_batch
    from tests.stage3_fakes import MechanicalInvestigator

    t2 = sorted(c for c, e in dev_ground_truth.items() if e["tier"] == "T2")[:T2_SAMPLE]
    t3 = sorted(c for c, e in dev_ground_truth.items() if e["tier"] == "T3")[:T3_SAMPLE]
    selected = tuple(sorted([*t2, *t3]))

    directory = tmp_path_factory.mktemp("stage4-corpus")
    with LedgerStore(":memory:") as store:
        batch = process_batch(store=store, benchmark_dir=benchmark_dir, split="dev")
        run_stage3(
            store=store,
            batch_result=batch,
            chain=ProviderChain((MechanicalInvestigator(),)),
            cache=TrajectoryCache(directory),
            case_ids=frozenset(selected),
        )
    return {"dir": directory, "t2": tuple(t2), "t3": tuple(t3), "all": selected}


